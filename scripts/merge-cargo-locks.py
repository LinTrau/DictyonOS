#!/usr/bin/env python3
"""Merge two Cargo.lock files into one de-duplicated lockfile.

Used by dictyonos/vendor.nix. rustPlatform.fetchCargoVendor accepts a single
lockfile, but the Asterinas kernel workspace and the cargo-osdk workspace each
have their own; the vendor tree has to cover both.

Only the [[package]] blocks are relevant to the fetcher, so they are copied
verbatim and de-duplicated on (name, version).
"""
import re
import sys


def blocks(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    for block in re.split(r"(?m)^(?=\[\[package\]\])", text):
        if block.startswith("[[package]]"):
            yield block.strip("\n")


def key_of(block):
    name = re.search(r'^name = "(.*)"', block, re.M)
    version = re.search(r'^version = "(.*)"', block, re.M)
    if not name or not version:
        return None
    return (name.group(1), version.group(1))


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: merge-cargo-locks.py OUT LOCK [LOCK...]")
    out, locks = sys.argv[1], sys.argv[2:]

    header = [
        "# @generated by dictyonos/scripts/merge-cargo-locks.py",
        "# Union of the Asterinas kernel and cargo-osdk lockfiles.",
        "version = 4",
        "",
    ]
    seen, merged, dropped = set(), [], 0
    for path in locks:
        for block in blocks(path):
            key = key_of(block)
            if key is None or key in seen:
                dropped += 1
                continue
            seen.add(key)
            merged.append(block)
    merged.sort()

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(header + merged) + "\n")
    print(f"merge-cargo-locks: {len(merged)} packages ({dropped} duplicates dropped)")


if __name__ == "__main__":
    main()
